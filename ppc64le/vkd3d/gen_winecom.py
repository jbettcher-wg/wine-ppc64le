# --------------------------------------------------------------------------
# struct bodies -- which ones reach an interface pointer, transitively
# --------------------------------------------------------------------------

TYPEDEF_HEAD = re.compile(r'typedef\s+(struct|union)\b[^{;]*\{')
FWD_IFACE = re.compile(r'typedef\s+struct\s+(I\w+)\s+\1\s*;')


def scan_structs(paths, iface_names):
    """-> (bearing, why).

    `bearing` is the set of struct type names that reach an interface pointer
    through any member chain.  Brace-MATCHED, not regexed: these headers nest
    nameless unions inside D3D12_RESOURCE_BARRIER and
    D3D12_TEXTURE_COPY_LOCATION, and a non-greedy regex records the inner
    union under __C89_NAMELESSUNIONNAME and loses the outer struct entirely.
    Every identifier in the whole body counts as a member type --
    over-approximating costs a refusal; under-approximating hands vkd3d a
    guest proxy pointer."""
    members = {}
    ifaces_seen = set(iface_names)
    for path in paths:
        with open(path, errors="replace") as fh:
            text = fh.read()
        ifaces_seen |= set(FWD_IFACE.findall(text))
        for m in TYPEDEF_HEAD.finditer(text):
            depth, i = 1, m.end()
            while i < len(text) and depth:
                if text[i] == '{':
                    depth += 1
                elif text[i] == '}':
                    depth -= 1
                i += 1
            body = text[m.end():i - 1]
            tail = re.match(r'\s*(\w+)\s*;', text[i:])
            if not tail:
                continue
            name = tail.group(1)
            if name in members:
                continue
            # SORTED: the `why` chain below lands in the refusal TEXT of the
            # generated header, and set order would make the committed file
            # depend on PYTHONHASHSEED.
            members[name] = sorted(
                set(re.findall(r'\b(\w+)\s*\*', body)) |
                set(re.findall(r'\b(\w+)\s+\w+\s*(?:\[|;|:)', body)))

    hit, why = {}, {}
    for name in members:
        seen, stack = set(), [(name, [])]
        while stack:
            cur, path = stack.pop()
            if cur in seen:
                continue
            seen.add(cur)
            for m in members.get(cur, ()):
                if m in ifaces_seen:
                    hit[name] = True
                    why[name] = " -> ".join(path + [cur, m])
                    stack = []
                    break
                if m in members:
                    stack.append((m, path + [cur]))
    return set(hit), why


# --------------------------------------------------------------------------
# parameter parsing
# --------------------------------------------------------------------------

class Param:
    __slots__ = ("raw", "base", "stars", "inner_const", "array", "name")

    def __init__(self, raw):
        self.raw = " ".join(raw.split())
        t = self.raw
        self.array = bool(re.search(r'\[', t))
        t = re.sub(r'\[[^\]]*\]', '', t).strip()
        # `Iface *const *p`: the INNER pointer is const, which is how these
        # headers spell an INPUT array.
        self.inner_const = bool(re.search(r'\*\s*const\s*\*', t))
        t = re.sub(r'\bconst\b', ' ', t)
        toks = t.replace('*', ' * ').split()
        self.stars = toks.count('*')
        toks = [x for x in toks if x != '*']
        self.base = toks[0] if toks else ''
        self.name = toks[-1] if len(toks) > 1 else ''
        if self.base in POINTER_TYPEDEFS:
            self.stars += 1
            self.base = POINTER_TYPEDEFS[self.base]
        if self.array:
            self.stars += 1

    def is_riid(self):
        return re.match(r'^(REFIID|REFGUID|REFCLSID)\b', self.raw) is not None


def resolve_alias(p):
    if p.base in IFACE_ALIASES:
        p.base = IFACE_ALIASES[p.base]


# The roster spells parameters in vkd3d's snake_case: command_list_count,
# num_objects, buffer_count, region_count.
COUNT_RE = re.compile(r'^(num_?\w*|\w*_?count\w*)$', re.IGNORECASE)


def find_count(params, idx):
    """Index of the by-value count that governs the array at `idx`: nearest
    preceding, else nearest following.  None if there is none."""
    cands = [i for i, p in enumerate(params)
             if p.stars == 0 and p.base in ("UINT", "UINT32", "unsigned",
                                            "int", "DWORD", "ULONG")
             and COUNT_RE.match(p.name or '')]
    before = [i for i in cands if i < idx]
    after = [i for i in cands if i > idx]
    if before:
        return before[-1]
    if after:
        return after[0]
    return None


# --------------------------------------------------------------------------
# classification
# --------------------------------------------------------------------------

CA = dict(PASS=0, IFACE_IN=1, RIID=2, PPV_OUT=3, RET_PTR=4, EVENT=5,
          IFACE_ARR_IN=6, IFACE_OUT_STATIC=7, IFACE_ARR_OUT_STATIC=8)
CA_NAME = {v: "WINECOM_CA_" + k for k, v in CA.items()}


class Refused(Exception):
    pass


class Plan:
    """What classify() proved about one slot.  No fp_reason / no reverse
    lane on this surface: the invoker crosses a unixlib and the surface
    lacks WINECOM_SF_REVERSE, so a by-value float is a plain Refused."""

    __slots__ = ("cls", "xaux", "caux", "aux", "aux2", "xmask",
                 "narrowmask", "narrowwide", "narrowsign", "narrow_params",
                 "dwordmask", "dwordsign", "ret_via_arg")

    def __init__(self):
        self.cls = self.xaux = self.caux = None
        self.aux = self.aux2 = 0
        self.xmask = 0
        self.narrowmask = self.narrowwide = self.narrowsign = 0
        self.narrow_params = []
        self.dwordmask = self.dwordsign = 0
        self.ret_via_arg = False


def classify(key, slot, ifaces, iface_index, byval_ok, dword_signed,
             bearing, why_bearing):
    """-> Plan, or raise Refused(reason)."""
    params = [Param(p) for p in slot["params"]]
    for p in params:
        resolve_alias(p)
    n = len(params)
    cls = [CA["PASS"]] * n
    xaux = [0] * n
    caux = [0] * n
    aux = aux2 = 0
    plan = Plan()

    if slot.get("aggregate_return"):
        # widl's __ret pointer: the caller's temporary, always parameter 0;
        # the runtime answers RAX = args[1] (WINECOM_F_RET_VIA_ARG).
        if not params or params[0].name != "__ret":
            raise Refused(
                "is marked aggregate_return but its first parameter is not "
                "the widl __ret pointer; the roster and this generator "
                "disagree and the safe answer is no")
        cls[0] = CA["RET_PTR"]
        plan.ret_via_arg = True

    if FLOAT_TOKENS.search(slot["ret"]) and "*" not in slot["ret"]:
        raise Refused(
            "returns %s by value; the unixlib invoker calls the host vtable "
            "slot in the widest INTEGER form, so the result would come back "
            "out of the wrong register file" % slot["ret"])
    if slot["ret"] != "void" and not slot.get("aggregate_return"):
        rp = Param(slot["ret"])
        if rp.stars == 0 and rp.base not in byval_ok:
            raise Refused(
                "return type %s is not provably integer-class on both ABIs; "
                "refusing rather than assuming" % slot["ret"])

    for i, p in enumerate(params):
        if cls[i] == CA["RET_PTR"]:
            continue
        if p.stars == 0:
            if p.base == "HANDLE" and key in EVENT_SLOTS:
                cls[i] = CA["EVENT"]
                continue
            if FLOAT_TOKENS.search(p.raw):
                raise Refused(
                    "passes %s by value; the unixlib invoker calls the host "
                    "vtable slot in the widest INTEGER form, so a float "
                    "argument would be placed in the wrong register file "
                    "entirely.  Serving it takes a hand-written stub, the "
                    "kind ClearDepthStencilView has always waited for"
                    % p.base)
            if p.base in GUEST_CODE_BYVAL:
                raise Refused(GUEST_CODE_BYVAL[p.base])
            if p.base in BYVAL_AGGREGATE:
                cls[i] = CA["PASS"]
                continue
            if p.base in BYVAL_ABI_SPLIT:
                raise Refused(BYVAL_ABI_SPLIT[p.base])
            if p.base not in byval_ok:
                raise Refused(
                    "by-value %s is not provably integer-class on both ABIs; "
                    "refusing rather than assuming it is an enum" % p.base)
            narrow = narrow_of(p)
            if narrow:
                if i >= 8:
                    raise Refused(
                        "passes a %d-byte %s by value in argument position "
                        "%d, past the eight parameters the narrowing masks "
                        "cover" % (narrow[0], p.base, i + 1))
                plan.narrowmask |= 1 << i
                if narrow[0] == 2:
                    plan.narrowwide |= 1 << i
                if narrow[1]:
                    plan.narrowsign |= 1 << i
                plan.narrow_params.append((i, p.base, narrow[0], narrow[1]))
            elif re.search(r'\blong\s+long\b', p.raw):
                pass    # 8 bytes; Param.base kept only the first `long`
            elif p.base in DWORD_UNSIGNED or p.base in dword_signed:
                # Four bytes: clean in a register, stale-topped on the stack
                # -- see DWORD_UNSIGNED above for the CopyDescriptors
                # measurement.  Sixteen mask bits cover every argc here.
                if i >= 16:
                    raise Refused(
                        "passes a 4-byte %s by value in argument position %d, "
                        "past the sixteen parameters dwordmask covers"
                        % (p.base, i + 1))
                plan.dwordmask |= 1 << i
                if p.base in dword_signed:
                    plan.dwordsign |= 1 << i
            elif p.base not in QWORD_BYVAL:
                raise Refused(
                    "by-value %s is integer-class but this generator has no "
                    "measured width for it; a 32-bit stack slot passed whole "
                    "carries the guest's leftovers above bit 31, so the width "
                    "must be known, not assumed" % p.base)
            cls[i] = CA["PASS"]
            continue

        # ---- pointers
        if p.base in CARRIER_STRUCTS:
            raise Refused("%s is %s" % (p.base, CARRIER_STRUCTS[p.base]))
        if p.base in bearing:
            raise Refused(
                "%s carries interface pointers inside a struct (%s) and has "
                "no hand-written walker; the pointers inside it would reach "
                "vkd3d as guest proxies"
                % (p.base, why_bearing.get(p.base, p.base)))

        if p.base == "void" and p.stars == 2:
            prev = params[i - 1] if i else None
            if prev is not None and prev.is_riid():
                cls[i] = CA["PPV_OUT"]
                cls[i - 1] = CA["RIID"]
                aux = i - 1
                continue
            if key in VOID_PP_IS_MEMORY:
                cls[i] = CA["PASS"]
                continue
            raise Refused(
                "has a void** out-parameter (`%s`) with no REFIID beside it "
                "to type the result; an untyped interface pointer cannot be "
                "given a guest vtable" % p.raw)

        if p.base in ifaces:
            if p.stars == 1:
                # The TYPE is recorded (xaux/xmask) even though the forward
                # direction identifies an IN pointer by identity: the mask is
                # what lets a FUTURE reverse lane fail closed per-parameter
                # instead of per-surface.
                cls[i] = CA["IFACE_IN"]
                xaux[i] = iface_index[p.base]
                plan.xmask |= 1 << i
                continue
            if p.stars != 2:
                raise Refused(
                    "takes `%s`: an interface pointer at a level of "
                    "indirection this generator has no class for" % p.raw)
            if p.inner_const:
                c = find_count(params, i)
                if c is None:
                    raise Refused(
                        "takes the input interface array `%s` with no "
                        "by-value count parameter to bound it" % p.raw)
                cls[i] = CA["IFACE_ARR_IN"]
                aux2 = c
                continue
            c = find_count(params, i)
            plural = (p.name or '').endswith("s")
            if c is not None and plural:
                cls[i] = CA["IFACE_ARR_OUT_STATIC"]
                xaux[i] = iface_index[p.base]
                plan.xmask |= 1 << i
                caux[i] = c
                continue
            if plural:
                raise Refused(
                    "writes the interface array `%s` with no count parameter "
                    "this generator can identify; refusing rather than "
                    "wrapping only its first element" % p.raw)
            cls[i] = CA["IFACE_OUT_STATIC"]
            xaux[i] = iface_index[p.base]
            plan.xmask |= 1 << i
            continue

        # A pointer to a pointer that is not an interface out-parameter must
        # be named before it may pass: this is where an unrecognised
        # interface spelling would silently become a native vtable in the
        # guest's hands.
        if p.stars >= 2 and p.base not in PLAIN_PP:
            raise Refused(
                "writes `%s`, a pointer-to-pointer whose pointee this "
                "generator cannot prove is plain memory rather than an "
                "interface; add it to PLAIN_PP with the reason, or give it a "
                "marshal class" % p.raw)

        # An ordinary pointer to plain data crosses as an address: guest
        # memory IS host memory on this port, WCHAR is two bytes on both
        # sides of this surface, and the descriptor structs come from the
        # same vkd3d headers both halves compile.
        cls[i] = CA["PASS"]

    plan.cls, plan.xaux, plan.caux = cls, xaux, caux
    plan.aux, plan.aux2 = aux, aux2
    return plan


