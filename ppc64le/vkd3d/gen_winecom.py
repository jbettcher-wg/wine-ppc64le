# FOUR-BYTE by-value types, split by signedness -- winecom_slot::dwordmask /
# dwordsign.  A 32-bit argument is clean in a register (x86-64 zero-extends
# 32-bit register writes) but NOT on the stack, where the guest's 32-bit
# store leaves the slot's upper half stale.  [MEASURED] on THIS surface:
# ID3D12Device::CopyDescriptors passes the descriptor heap type as argument
# seven -- a stack slot -- and vkd3d's 64-bit switch missed an enum whose low
# half said 0, printing "Unhandled descriptor heap type 0" 32768 times per
# scene while every descriptor copy silently did nothing.  The roster's enums
# join DWORD_SIGNED at run time (an enum is int underneath).
#
# Every by-value type must land in exactly one of: NARROW_BYVAL, these two,
# QWORD_BYVAL, BYVAL_AGGREGATE -- a byval_ok type with no width is refused,
# because "probably 32 bits" is how a stack slot's stale upper half reaches a
# callee that trusts it.
DWORD_UNSIGNED = frozenset("""
    UINT ULONG DWORD BOOL WINBOOL UINT32 DXGI_USAGE unsigned
""".split())
DWORD_SIGNED = frozenset("""
    INT LONG INT32 HRESULT int long
""".split())
QWORD_BYVAL = frozenset("""
    UINT64 INT64 SIZE_T SSIZE_T LONGLONG ULONGLONG ULONG64 LONG64 QWORD
    HANDLE HWND HMODULE HMONITOR ULONG_PTR DWORD_PTR UINT_PTR LONG_PTR
    INT_PTR D3D12_GPU_VIRTUAL_ADDRESS
""".split())

# By-value integers NARROWER THAN 32 BITS: (bytes, signed).  MS-x64 leaves
# the upper bits of the register UNDEFINED and makes ignoring them the
# CALLEE's job; ELFv2 makes extending them the CALLER's job and a ppc64
# callee trusts that it happened.  The runtime does the extension
# (struct winecom_slot::narrowmask); this table tells it width and
# signedness.  [MEASURED] on the MF surface: IWMSyncReader::GetStreamSelected
# read a guest-passed WORD 1 as 0x40000001.  This roster has UINT8 parameters
# (ID3D12StateObjectProperties1 and friends), so unlike the DXVK copy the
# masks are emitted here, not merely recognised.
NARROW_BYVAL = {
    "WORD":    (2, False), "USHORT": (2, False), "UINT16":  (2, False),
    "SHORT":   (2, True),  "INT16":  (2, True),
    "BYTE":    (1, False), "UCHAR":  (1, False), "UINT8":   (1, False),
    "BOOLEAN": (1, False),
    "CHAR":    (1, True),  "INT8":   (1, True),
}

NARROW_RAW = (
    (r'\bunsigned\s+short\b',  (2, False)),
    (r'\bsigned\s+short\b',    (2, True)),
    (r'\bunsigned\s+char\b',   (1, False)),
    (r'\bsigned\s+char\b',     (1, True)),
    (r'\bshort\b',              (2, True)),
    (r'\bchar\b',               (1, True)),
)


def narrow_of(p):
    """(bytes, signed) for a by-value parameter narrower than 32 bits, else None."""
    if p.base in NARROW_BYVAL:
        return NARROW_BYVAL[p.base]
    for pat, w in NARROW_RAW:
        if re.search(pat, p.raw):
            return w
    return None


