def c_guid(u):
    a, b, c, d, e = u.split("-")
    d4 = d + e
    return "{0x%s,0x%s,0x%s,{%s}}" % (
        a, b, c, ",".join("0x" + d4[i:i + 2] for i in range(0, 16, 2)))


def generate(roster, prefix, header_dir):
    ifaces = roster["interfaces"]
    order = sorted(ifaces)
    iface_index = {n: i for i, n in enumerate(order)}
    byval_ok = (set(BYVAL_INTEGER) | set(roster["enums"])
                | set(TYPEDEF_INTEGER))
    dword_signed = set(DWORD_SIGNED) | set(roster["enums"])
    # Scan every header the roster's interfaces were generated from.  A
    # missing directory is a HARD ERROR: a struct whose definition the scan
    # never saw is not refused -- it is PASSED THROUGH, the one outcome this
    # generator exists to prevent.
    if not os.path.isdir(header_dir):
        sys.exit("gen_winecom: %s is not a directory.  The vkd3d widl "
                 "headers are generated by ppc64le/vkd3d/gen-headers.sh; "
                 "generating without them silently drops every struct "
                 "refusal." % header_dir)
    paths = [os.path.join(header_dir, f) for f in sorted(os.listdir(header_dir))
             if f.endswith(".h")]
    bearing, why_bearing = scan_structs(paths, set(ifaces))
    hand_index, hand_order = {}, []
    for key, fn in HAND_SLOTS:
        if fn not in hand_order:
            hand_order.append(fn)
        hand_index[key] = hand_order.index(fn)

    out = []
    w = out.append
    stats = dict(marshalled=0, refused=0, hand=0, identity=0, iunknown=0)
    refusal_log = []
    narrow_log = []

    w("""/* GENERATED by ppc64le/vkd3d/gen_winecom.py -- do not edit.
 *
 * Marshal tables for the %s surface (%d interfaces, %d vtable slots),
 * generated from ppc64le/vkd3d/interfaces_d3d12.json -- the same roster
 * dlls/d3d12/d3d12.thunks hands spec2thunk to build the guest trap
 * module.  Interface order is sorted by name, which is the order
 * spec2thunk COM mode gives the guest stub arrays; libs/winecom
 * cross-checks every IID and slot count at attach, so the two
 * generators cannot silently disagree.
 *
 * Slot/iface types and WINECOM_CA_* classes come from
 * include/wine/winecom.h, which must be included before this file.
 */
""" % (roster["surface"], len(order),
       sum(len(ifaces[n]["slots"] or ()) for n in order)))

    w("enum %s_iface_index\n{" % prefix)
    for n in order:
        w("    %s_IFACE_%s = %d," % (prefix.upper(), n, iface_index[n]))
    w("    %s_IFACE_COUNT = %d\n};\n" % (prefix.upper(), len(order)))
    w("#define %s_HAND_COUNT %d\n" % (prefix.upper(), len(hand_order)))
    if hand_order:
        w("/* hand_funcs[] order in dlls/d3d12/main.c:\n%s */\n"
          % "".join("     *   %d %s\n" % (i, f)
                    for i, f in enumerate(hand_order)))

    tables = []
    for n in order:
        slots = ifaces[n]["slots"]
        rows, decls = [], []
        for s in slots:
            key = "%s::%s" % (s["owner"], s["name"])
            if s["slot"] < 3:
                rows.append('    { "%s", NULL, NULL, NULL, %d, 0, 0, 0, NULL,'
                            ' 0, 0, 0 },  /* runtime */'
                            % (key, 1 if s["slot"] else 3))
                stats["iunknown"] += 1
                continue
            argc = 1 + len(s["params"])
            flags = []
            if s["ret"] == "void":
                flags.append("WINECOM_F_RET_VOID")
            if key in hand_index:
                rows.append('    { "%s", NULL, NULL, NULL, %d,'
                            ' WINECOM_F_HAND, %d, 0, NULL, 0, 0, 0 },'
                            % (key, argc, hand_index[key]))
                stats["hand"] += 1
                continue
            plan = None
            reason = REFUSALS.get(key)
            if reason is None:
                try:
                    plan = classify(key, s, ifaces, iface_index, byval_ok,
                                    dword_signed, bearing, why_bearing)
                except Refused as e:
                    reason = str(e)
            if reason is not None:
                rows.append('    { "%s",\n      "%s: %s",\n'
                            '      NULL, NULL, %d, 0, 0, 0, NULL, 0, 0, 0 },'
                            % (key, key, reason.replace('"', "'"), argc))
                stats["refused"] += 1
                refusal_log.append((n, s["slot"], key, reason))
                continue
            if plan.ret_via_arg:
                flags.append("WINECOM_F_RET_VIA_ARG")
            cls, xaux, caux = plan.cls, plan.xaux, plan.caux
            cname = xname = kname = "NULL"
            if any(c != CA["PASS"] for c in cls):
                cname = "cls_%s_%d" % (n, s["slot"])
                decls.append("static const unsigned char %s[] = { %s };"
                             % (cname, ", ".join(CA_NAME[c] for c in cls)))
            # Emitted whenever a parameter is interface-typed, NOT when the
            # values happen to be non-zero: roster index 0 is a real
            # interface and `any(xaux)` would drop the row that names it.
            if plan.xmask:
                xname = "xaux_%s_%d" % (n, s["slot"])
                decls.append("static const unsigned char %s[] = { %s };"
                             % (xname, ", ".join(str(x) for x in xaux)))
            if any(caux):
                kname = "caux_%s_%d" % (n, s["slot"])
                decls.append("static const unsigned char %s[] = { %s };"
                             % (kname, ", ".join(str(x) for x in caux)))
            for np in plan.narrow_params:
                narrow_log.append((key,) + np)
            rows.append('    { "%s", NULL, %s, %s, %d, %s, %d, %d, %s, 0, 0,'
                        ' 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%04x, 0x%04x },'
                        % (key, cname, xname, argc,
                           "|".join(flags) or "0", plan.aux, plan.aux2, kname,
                           plan.xmask, plan.narrowmask, plan.narrowwide,
                           plan.narrowsign, plan.dwordmask, plan.dwordsign))
            stats["marshalled"] += 1

        if len(slots) <= 3:
            # Only IUnknown itself: its three slots are served by the runtime
            # from the proxy table without crossing.  Every OTHER interface
            # gets a real table -- a NULL table refuses every slot, which is
            # exactly the Device1..Device15 hole this generator was written
            # to close.
            stats["identity"] += 1
            tables.append((n, None))
            continue
        tables.append((n, (decls, rows)))

    for n, t in tables:
        if t is None:
            continue
        decls, rows = t
        w("")
        for d in decls:
            w(d)
        w("static const struct winecom_slot slots_%s[%d] =\n{" % (n, len(rows)))
        for r in rows:
            w(r)
        w("};")

    w("\nstatic const struct winecom_iface %s_com_ifaces[%s_IFACE_COUNT] =\n{"
      % (prefix, prefix.upper()))
    for n, t in tables:
        w('    { "%s", %s,\n      %d, %s, 0 },'
          % (n, c_guid(ifaces[n]["uuid"]), len(ifaces[n]["slots"]),
             "NULL" if t is None else "slots_" + n))
    w("};")

    w("\n/* %d slot(s) marshalled, %d hand-written, %d refused with a named\n"
      " * reason, %d IUnknown slot(s) served by the runtime; %d interface(s)\n"
      " * (IUnknown itself) carry identity rows only. */"
      % (stats["marshalled"], stats["hand"], stats["refused"],
         stats["iunknown"], stats["identity"]))
    return "\n".join(out) + "\n", stats, refusal_log, narrow_log


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roster",
                    default=os.path.join(HERE, "interfaces_d3d12.json"))
    ap.add_argument("--headers",
                    default=os.path.join(HERE, "generated-headers"),
                    help="directory holding vkd3d's widl-generated headers")
    ap.add_argument("--prefix", default="d3d12")
    ap.add_argument("--out")
    ap.add_argument("--check", metavar="FILE")
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()

    with open(args.roster) as fh:
        roster = json.load(fh)
    text, stats, refusals, narrows = generate(roster, args.prefix,
                                              args.headers)

    print("surface %s: %d marshalled, %d hand-written, %d refused, "
          "%d IUnknown, %d identity-only interface(s)"
          % (roster["surface"], stats["marshalled"], stats["hand"],
             stats["refused"], stats["iunknown"], stats["identity"]))

    if args.report:
        print("\nnarrow by-value parameters (extended by the runtime):")
        for key, i, base, width, signed in narrows:
            print("  %-60s arg %d: %d-byte %s%s"
                  % (key, i + 1, width, "signed " if signed else "", base))
        print("\nrefused slots, by reason:")
        seen = {}
        for n, slot, key, reason in refusals:
            seen.setdefault(reason.split(';')[0][:76], []).append(key)
        for reason, keys in sorted(seen.items(), key=lambda kv: -len(kv[1])):
            uniq = sorted(set(keys))
            print("  %4d  %s" % (len(keys), reason))
            for k in uniq[:8]:
                print("          %s" % k)
            if len(uniq) > 8:
                print("          ... and %d more distinct method(s)"
                      % (len(uniq) - 8))

    if args.check:
        with open(args.check) as fh:
            have = fh.read()
        if have == text:
            print("\ncheck passed: %s matches the roster" % args.check)
            return 0
        sys.exit("\ngen_winecom: %s has DRIFTED from the roster.  Regenerate "
                 "it (--out) and re-run every gate." % args.check)

    if args.out:
        with open(args.out, "w") as fh:
            fh.write(text)
        print("\nwrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
